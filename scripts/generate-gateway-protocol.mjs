import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const protocolRef = process.env.ASTER_PROTOCOL_REF || "main";
const sourceBase = `https://raw.githubusercontent.com/grampr/Aster-protocol/${encodeURIComponent(protocolRef)}/packages/protocol-ts/src/generated`;
const outputDirectory = new URL("../src/generated/", import.meta.url);
const artifacts = [
  ["gateway.ts", "aster-gateway.ts", "automatically generated by json-schema-to-typescript"],
  ["gateway-constants.ts", "aster-gateway-constants.ts", "generated from the Gateway JSON Schemas"],
];

await mkdir(outputDirectory, { recursive: true });

for (const [sourceName, outputName, expectedBanner] of artifacts) {
  const response = await fetch(`${sourceBase}/${sourceName}`);
  if (!response.ok) {
    throw new Error(`Failed to download ${sourceName}: ${response.status} ${response.statusText}`);
  }
  const source = await response.text();
  if (!source.includes(expectedBanner)) {
    throw new Error(`Refusing to write ${outputName}: generated-file banner was not found`);
  }
  await writeFile(fileURLToPath(new URL(outputName, outputDirectory)), source);
}

console.log(`Generated ${artifacts.length} Gateway artifacts from Aster-protocol@${protocolRef}.`);
